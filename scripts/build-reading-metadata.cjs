// Extract chapter boundaries without rewriting or evaluating individual records.
const fs = require('node:fs');
const vm = require('node:vm');
const crypto = require('node:crypto');
const path = require('node:path');
const root = path.join(__dirname, '..');
function scan(source) {
  let quote = null, escaped = false, depth = 0, start = null, chapter = 0;
  const records = [];
  for (let i = source.indexOf('[') + 1; i < source.length; i++) {
    const char = source[i], next = source[i + 1];
    if (quote) {
      if (escaped) escaped = false;
      else if (char === '\\') escaped = true;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === '/' && next === '/') {
      let end = source.indexOf('\n', i); if (end < 0) end = source.length;
      if (!depth) {
        const match = source.slice(i, end).match(/CAP[ÍI]TULO\s+(\d+)/i);
        if (match) chapter = Number(match[1]);
      }
      i = end - 1; continue;
    }
    if (char === '/' && next === '*') { i = source.indexOf('*/', i + 2) + 1; continue; }
    if (char === "'" || char === '"' || char === '`') { quote = char; continue; }
    if (char === '{') { if (depth === 0) start = i; depth++; }
    if (char === '}') {
      depth--;
      if (!depth && start !== null) { records.push({ chapter, text: source.slice(start, i + 1) }); start = null; }
    }
  }
  return records;
}
function signature(value) {
  let hash = 2166136261;
  for (const char of JSON.stringify(value)) { for (let i = 0; i < char.length; i++) hash = Math.imul(hash ^ char.charCodeAt(i), 16777619); }
  return (hash >>> 0).toString(16);
}
const files = {};
for (const [file, name] of [['book2/nodes.js', 'nodesBook2'], ['book2/links.js', 'linksBook2']]) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const records = scan(source), ctx = vm.createContext({}); vm.runInContext(source, ctx);
  const data = vm.runInContext(name, ctx);
  if (records.length !== data.length) throw Error(`Record scan mismatch: ${file}`);
  const chapters = records.map((record, i) => {
    // A cumulative record may explicitly contain later material than its heading.
    const ownBookReferences = [...record.text.matchAll(/LIBRO\s+2\s*,?\s*CAP[ÍI]TULO\s+(\d+)/gi)].map(m => Number(m[1]));
    return Math.max(record.chapter, Number.isInteger(data[i].chapter) ? data[i].chapter : 0, ...ownBookReferences);
  });
  if (file === 'book2/links.js') {
    if (data[7].source !== 'breca' || data[7].target !== 'ulfhednar') throw Error('Review Breca lineage override');
    chapters[7] = 1; // The cast confirms Tainted; wolf blood is confirmed by Orka in chapter 1.
  }
  files[file] = { signatures: data.map(signature), sha256: crypto.createHash('sha256').update(source).digest('hex'), chapters };
  const delayed = chapters.map((chapter, i) => ({ id: data[i].id, from: records[i].chapter, to: chapter })).filter(x => x.to !== x.from);
  console.log(file, 'records:', records.length, 'conservatively delayed:', JSON.stringify(delayed));
}
const output = '// Generated by node scripts/build-reading-metadata.cjs. Do not edit by hand.\nconst READING_METADATA = ' + JSON.stringify({ version: 1, files }, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'reading-metadata.js'), output);
module.exports = { scan };
